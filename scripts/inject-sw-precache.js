#!/usr/bin/env node
/**
 * inject-sw-precache.js  (runs after `vite build`)
 *
 * This file is the ONLY source of the shipped service worker. There used to be a second
 * copy at public/sw.js, which Vite dutifully copied to dist/ for this script to overwrite
 * a moment later — so it looked authoritative, was the obvious file to edit, and had no
 * effect on anything. It has been deleted. Edit the template below.
 *
 * Problem solved: a handwritten service worker precaches only
 * the four static shell URLs. Vite emits hashed JS/CSS bundles like
 * /assets/index-Bx3kQ9aR.js whose filenames change on every build. Because the
 * SW never sees those URLs at install time, an offline first-load finds the HTML
 * shell in cache but fails to fetch the JS/CSS — the app does not boot.
 *
 * Fix: after vite build, this script reads the hashed filenames out of dist/assets/
 * and rewrites dist/sw.js so the install handler caches the exact URLs for this build.
 * The SW template lives here rather than in public/ so it can reference the generated
 * array without a hand-maintained placeholder.
 */

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, extname } from 'node:path';

const DIST = new URL('../dist', import.meta.url).pathname;

async function main() {
  // Collect hashed assets Vite emitted under dist/assets/
  let assetFiles = [];
  try {
    const entries = await readdir(join(DIST, 'assets'));
    // Every hashed asset the bundle imports, not just code. The font matters because
    // Inter is self-hosted (see index.css), so without it an offline first-load boots
    // the app in the fallback system face. Images matter because the bar-card renderer
    // draws the brand lockup, and a card missing its mark is a worse card to share.
    // Anything Vite emits into assets/ is by definition something the build references.
    assetFiles = entries
      .filter(f => ['.js', '.css', '.woff2', '.woff', '.png', '.svg', '.webp', '.txt'].includes(extname(f)))
      // Except the Capacitor plugin bundle. It is only ever imported inside the native
      // shell, where the service worker does not run at all — precaching it would make
      // every browser download plugin code it can never execute, and a failed fetch of it
      // would abort the whole install and leave the app with no offline support.
      // The chunk name is pinned in vite.config.js so this stays a name match, not a guess.
      .filter(f => !f.startsWith('capacitor-native'))
      .map(f => `/assets/${f}`);
  } catch {
    console.warn('[inject-sw-precache] dist/assets not found — skipping asset injection');
  }

  // Full precache set: shell URLs + this build's hashed assets
  // Every icon the manifest references, so an install initiated while offline still
  // finds its artwork. og-image.png is deliberately absent — only crawlers read it.
  const shellUrls = ['/', '/manifest.json', '/icon-192.png', '/icon-512.png', '/icon-maskable-512.png'];
  const allUrls = [...shellUrls, ...assetFiles];

  // Read the cache-version stamp from package.json so bumping the npm version
  // automatically busts old service-worker caches in the field.
  let version = 'barsmith-v1';
  try {
    const pkg = JSON.parse(await readFile(new URL('../package.json', import.meta.url).pathname, 'utf8'));
    version = `barsmith-${pkg.version}`;
  } catch {}

  const sw = `// ─────────────────────────────────────────────
// SERVICE WORKER — generated by scripts/inject-sw-precache.js
// Do not edit this file by hand; edit scripts/inject-sw-precache.js or vite.config.js.
//
// Goal: once a writer has opened Barsmith online, the entire writing-gym loop
// (word flashing, timer/BPM, Bar Pad, Vault, History) keeps working with zero
// connectivity.  Dictionary/rhyme lookups still need a network and degrade
// gracefully in the app — this worker does not intercept those requests.
//
// Strategy:
//   Navigations  — network-first, fallback to cached shell when offline.
//   Same-origin assets (hashed JS/CSS, icons, manifest)
//               — cache-first, refreshed stale-while-revalidate.
//               — The PRECACHE list below is injected at build time so EVERY
//                 asset this exact build needs is cached during install.  This
//                 is what makes offline-on-first-visit actually work.
//   Cross-origin (dictionaryapi.dev, api.datamuse.com) — network only, untouched.
// ─────────────────────────────────────────────

const CACHE_VERSION = ${JSON.stringify(version)};

// Exact asset URLs for this build, injected by scripts/inject-sw-precache.js.
const PRECACHE = ${JSON.stringify(allUrls, null, 2)};

self.addEventListener('install', (event) => {
  // A rejected waitUntil promise causes the browser to abort installation and retry
  // later, which is the correct behaviour. Do NOT catch here — a partial cache that
  // activates would serve a broken offline experience. Let it fail loudly.
  event.waitUntil(
    caches.open(CACHE_VERSION).then((cache) => cache.addAll(PRECACHE))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_VERSION).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return; // never intercept dictionary/rhyme API calls

  if (request.mode === 'navigate') {
    // Only the app shell may be stored under '/'. This used to cache EVERY navigation
    // response there, which was harmless while the app was the only page on the origin
    // and quietly poisoned the offline boot as soon as a second one existed (the privacy
    // policy) — an offline launch would have served a legal page instead of the app.
    const isAppShell = url.pathname === '/' || url.pathname === '/index.html';
    event.respondWith(
      fetch(request)
        .then((res) => {
          if (isAppShell && res.ok) {
            const copy = res.clone();
            caches.open(CACHE_VERSION).then((cache) => cache.put('/', copy)).catch(() => {});
          }
          return res;
        })
        // Offline: serve that page if it happens to be cached, otherwise the app shell,
        // which is the one page guaranteed to work without a connection.
        .catch(() => caches.match(request).then((hit) => hit || caches.match('/')))
    );
    return;
  }

  // Stale-while-revalidate for all same-origin assets.
  // Vite content-hashes mean a cached asset is always exactly right or superseded,
  // so serving the cached copy first and refreshing in the background is always safe.
  event.respondWith(
    caches.match(request).then((cached) => {
      const network = fetch(request)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE_VERSION).then((cache) => cache.put(request, copy)).catch(() => {});
          }
          return res;
        })
        .catch(() => cached);
      return cached || network;
    })
  );
});
`;

  await writeFile(join(DIST, 'sw.js'), sw, 'utf8');
  console.log(`[inject-sw-precache] Wrote dist/sw.js — ${allUrls.length} URLs precached (version: ${version})`);
}

main().catch((e) => { console.error('[inject-sw-precache]', e); process.exit(1); });
